const cache = {};

export async function fetchFishInfo(fishName) {
  if (cache[fishName]) {
    return cache[fishName];
  }
  const localInfo = fishDetailsDB[fishName] || {};
  const result = {
    name: fishName,
    status: localInfo.status || "🟢 Найменший ризик (LC)",
    bait: localInfo.bait || "Живець, хробак, базові принади",
    description: localInfo.description || "Прісноводна риба, поширена у водоймах даного регіону.",
    fact: localInfo.fact || "Цей вид є важливим елементом екосистеми даної водойми."
  };

  cache[fishName] = result;
  return result;
}